"""Writes the list of Rust crates QuickCopy depends on, with their licenses,
into THIRD-PARTY-NOTICES.md between the `crates:begin` and `crates:end`
markers. The rest of that file is written by hand.

    python tools/third_party.py

Reads `cargo metadata` for the Windows x64 target with Cargo.lock as it is
(--locked), so the list matches what a release build compiles. Crates
reached only through build-dependencies (build.rs) are listed apart: they
run while building and are not part of quickcopy.exe.
"""

import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOTICES = ROOT / "THIRD-PARTY-NOTICES.md"
TARGET = "x86_64-pc-windows-msvc"
BEGIN = "<!-- crates:begin (generated by tools/third_party.py, do not edit) -->"
END = "<!-- crates:end -->"


def metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET],
        cwd=ROOT, check=True, capture_output=True, text=True, encoding="utf-8",
    ).stdout
    return json.loads(out)


def closure(nodes, start, kinds):
    """Package ids reachable from `start`, following the first edge only if
    its kind is in `kinds` (None is a normal dependency) and any edge after."""
    seen, todo = set(), [start]
    first = True
    while todo:
        frontier, todo = todo, []
        for pid in frontier:
            for dep in nodes[pid]["deps"]:
                if first and not any(k["kind"] in kinds for k in dep["dep_kinds"]):
                    continue
                if dep["pkg"] not in seen:
                    seen.add(dep["pkg"])
                    todo.append(dep["pkg"])
        first = False
    return seen


def table(packages):
    rows = ["| Crate | Version | License | Source |", "| --- | --- | --- | --- |"]
    for p in sorted(packages, key=lambda p: (p["name"], p["version"])):
        license = p.get("license") or f"see {p.get('license_file') or 'the crate'}"
        source = p.get("repository") or f"https://crates.io/crates/{p['name']}"
        rows.append(f"| {p['name']} | {p['version']} | {license} | <{source}> |")
    return "\n".join(rows)


def main():
    meta = metadata()
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    normal = closure(nodes, root, {None})
    build = closure(nodes, root, {"build"}) - normal

    block = "\n\n".join([
        BEGIN,
        f"Dependencies of quickcopy.exe ({len(normal)} crates, including the proc-macro crates that run while compiling):",
        table(packages[i] for i in normal),
        f"Used only by build.rs while building ({len(build)} crates):",
        table(packages[i] for i in build),
        END,
    ])
    text = NOTICES.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(BEGIN) + ".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit(f"{NOTICES.name} has no {BEGIN!r} ... {END!r} block")
    NOTICES.write_text(pattern.sub(lambda _: block, text), encoding="utf-8", newline="\n")
    print(f"{NOTICES.name}: {len(normal)} crates in the exe, {len(build)} build-only")


if __name__ == "__main__":
    main()
