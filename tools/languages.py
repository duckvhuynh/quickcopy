URL = "https://translate-pa.googleapis.com/v1/supportedLanguages?client=gtx&display_language={}&key={}"
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "languages.rs")


def fetch(display):
    with urllib.request.urlopen(URL.format(display, KEY), timeout=15) as r:
        return [(x["language"], x["name"]) for x in json.load(r)["targetLanguages"]]


def rust(rows):
    return "\n".join(f"    ({json.dumps(code)}, {json.dumps(name, ensure_ascii=False)})," for code, name in rows)


def vietnamese(rows):
    """Every name starts with exactly one "Tiếng" (Google adds it to only a
    few), sorted by the name after it, ignoring diacritics."""
    import unicodedata

    def base(name):
        return name[len("Tiếng "):] if name.lower().startswith("tiếng ") else name

    def key(name):
        folded = unicodedata.normalize("NFD", base(name).replace("Đ", "D").replace("đ", "d"))
        return "".join(c for c in folded if not unicodedata.combining(c)).lower()

    # "Myanmar (tiếng Miến Điện)": no second "tiếng" inside the brackets.
    rows = [(code, "Tiếng " + base(name).replace("(tiếng ", "(")) for code, name in rows]
    return sorted(rows, key=lambda r: key(r[1]))


