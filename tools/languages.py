"""Regenerates src/languages.rs from Google Translate's language list.

Usage: python tools/languages.py
Fetches the target languages with English and Vietnamese display names,
in Google's order for each (alphabetical in that language).
"""
import datetime
import json
import os
import urllib.request

KEY = os.environ.get("QC_GOOGLE_KEY", "AIzaSyDLEeFI5OtFBwYBIoK_jj5m32rZK5CkCXA")
URL = "https://translate-pa.googleapis.com/v1/supportedLanguages?client=gtx&display_language={}&key={}"
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "languages.rs")


def fetch(display):
    with urllib.request.urlopen(URL.format(display, KEY), timeout=15) as r:
        return [(x["language"], x["name"]) for x in json.load(r)["targetLanguages"]]


def rust(rows):
    return "\n".join(f"    ({json.dumps(code)}, {json.dumps(name, ensure_ascii=False)})," for code, name in rows)


en, vi = fetch("en"), fetch("vi")
assert {c for c, _ in en} == {c for c, _ in vi}, "lists differ"
today = datetime.date.today().isoformat()
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write(f"""//! Google Translate's {len(en)} target languages, from its supportedLanguages
//! endpoint on {today}, in alphabetical order for each app language.
//! Generated by tools/languages.py; do not edit by hand.

/// (code, English name)
pub const EN: &[(&str, &str)] = &[
{rust(en)}
];

/// (code, Vietnamese name)
pub const VI: &[(&str, &str)] = &[
{rust(vi)}
];
""")
print(f"wrote {OUT}: {len(en)} languages")
